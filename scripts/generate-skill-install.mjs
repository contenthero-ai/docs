#!/usr/bin/env node
/**
 * Generates `skills/install.mdx`, the per-host skill install guide, from `@contenthero-ai/connect`.
 *
 *   node scripts/generate-skill-install.mjs          write the page
 *   node scripts/generate-skill-install.mjs --check  fail if the committed page differs (CI)
 *
 * ⭐ WHY GENERATED. The same per-host steps render in the app's Settings Developer tab and on
 * contenthero.ai/skills, both from `@contenthero-ai/connect`. A hand-written copy here would be the
 * third, and it would drift the first time a vendor renamed a screen: this page's previous version
 * told every host to clone the repo into a skills folder, which nested the skill one level too deep
 * to be found, for weeks after the installer stopped saying it.
 *
 * Order when anything changes: edit connect, publish it, bump the pin here, regenerate.
 * `check:currency` fails first if the pin is behind what is published.
 */

import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { MCP_HOSTS, SKILL_ZIP_URL, PLUGIN_ZIP_URL } from '@contenthero-ai/connect'

const CHECK = process.argv.includes('--check')
const OUT = join(new URL('..', import.meta.url).pathname, 'skills/install.mdx')

// A relative download (ChatGPT's icon) is served by the site that renders the installer, not by docs.
const SITE = 'https://contenthero.ai'
const abs = (href) => (href.startsWith('/') ? `${SITE}${href}` : href)
const indent = (text, n) => text.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n')

const step = (s) => {
  const parts = []
  if (s.body) parts.push(s.body)
  if (s.download) parts.push(`[${s.download.label}](${abs(s.download.href)})`)
  if (s.link) parts.push(`[${s.link.label}](${abs(s.link.href)})`)
  for (const f of s.copy ?? []) parts.push(`**${f.label}**\n\n\`\`\`\n${f.value}\n\`\`\``)
  if (s.code) parts.push(`\`\`\`${s.code.includes('\n') ? '' : 'bash'}\n${s.code}\n\`\`\``)
  return `      <Step title="${s.title}">\n${indent(parts.join('\n\n'), 8)}\n      </Step>`
}

const checked = (skill) =>
  skill.verifiedBy === 'install'
    ? `Tested by a real install on ${skill.verifiedOn}.`
    : `Checked against the host's own documentation on ${skill.verifiedOn}.`

const tabs = MCP_HOSTS.map(
  (h) => `  <Tab title="${h.name}">
    <Steps>
${h.skill.steps.map(step).join('\n')}
    </Steps>

    ${checked(h.skill)}
  </Tab>`,
).join('\n')

const page = `---
title: "Install the Skill"
description: "Install the ContentHero skill, or the plugin that brings the connector with it, on the AI you already use."
---

{/* GENERATED by scripts/generate-skill-install.mjs from @contenthero-ai/connect. Do not edit. */}

ContentHero ships as one plugin: the \`contenthero\` skill plus the ContentHero connector. Where your AI
installs plugins, one install brings both. Where it only takes a skill, install the skill and
[connect ContentHero](/mcp/overview) separately, because a skill on its own cannot bring a connector.

Every release publishes two files:

- [\`contenthero-plugin.zip\`](${PLUGIN_ZIP_URL}): the plugin, skill and connector together.
- [\`contenthero.zip\`](${SKILL_ZIP_URL}): the skill on its own.

<Tabs>
${tabs}
</Tabs>

## Updating

A plugin installed from the marketplace updates with the marketplace. An uploaded file is a
snapshot: download the new release and upload it again.

<Warning>
Never paste your API key into an agent chat. Use the connector, \`contenthero login\`, or the \`CONTENTHERO_API_KEY\` environment variable.
</Warning>
`

if (CHECK) {
  const committed = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (committed !== page) {
    console.error('skills/install.mdx is stale: run `npm run generate:skill-install` and commit the result.')
    process.exit(1)
  }
  console.log('skills/install.mdx matches @contenthero-ai/connect.')
} else {
  writeFileSync(OUT, page)
  console.log(`wrote skills/install.mdx (${MCP_HOSTS.length} hosts)`)
}
