#!/usr/bin/env node
/**
 * Generates `snippets/media-host.mdx`, the one host a person allows so their agent can download their files, from
 * `@contenthero-ai/connect`.
 *
 *   node scripts/generate-media-host.mjs          write the snippet
 *   node scripts/generate-media-host.mjs --check  fail if the committed snippet differs (CI)
 *
 * ⭐ WHY GENERATED. The same host is in the connect flow, in the instructions the MCP sends every agent, and in
 * the app's config, and the app's `agent-media-host-is-published` test holds those three together. A host
 * typed into a page here would be a fourth copy that nothing checks.
 *
 * Order when anything changes: edit connect, publish it, bump the pin here, regenerate.
 */

import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { MEDIA_HOST } from '@contenthero-ai/connect'

const CHECK = process.argv.includes('--check')
const OUT = join(new URL('..', import.meta.url).pathname, 'snippets/media-host.mdx')

const page = `{/* Generated by scripts/generate-media-host.mjs from @contenthero-ai/connect. Do not edit by hand. */}

\`\`\`
${MEDIA_HOST}
\`\`\`
`

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== page) {
    console.error('snippets/media-host.mdx is out of date. Run: npm run generate:media-host')
    process.exit(1)
  }
  console.log('snippets/media-host.mdx is current')
} else {
  writeFileSync(OUT, page)
  console.log('wrote snippets/media-host.mdx')
}
